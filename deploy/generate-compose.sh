#!/usr/bin/env bash
# generate-compose.sh — Generates docker-compose.yaml from TENANT_COUNT and
# immediately brings the stack up. This is the single command to (re-)deploy.
#
# Usage:
#   ./generate-compose.sh                  # use TENANT_COUNT from .env (default 5)
#   TENANT_COUNT=8 ./generate-compose.sh   # override inline
#   ./generate-compose.sh --no-up          # only generate, don't docker compose up
#
# Port layout:
#   platform-db is fixed at host port 5434.
#   Tenant DBs start at 5433 and skip 5434:
#     DB 1 -> 5433
#     DB 2 -> 5435
#     DB 3 -> 5436  ... DB N -> 5433 + N  (for N >= 2)

set -euo pipefail
cd "$(dirname "$0")"

# Save any caller-supplied TENANT_COUNT before .env potentially overwrites it
_CALLER_TENANT_COUNT="${TENANT_COUNT:-}"

# Load .env (if present) — supplies defaults for variables not already set
if [[ -f .env ]]; then
  while IFS='=' read -r key value; do
    [[ "$key" =~ ^#.*$ || -z "$key" ]] && continue
    # Only set if not already exported by the caller
    [[ -v "$key" ]] || export "$key"="$value"
  done < .env
fi

# Caller-supplied value wins over .env; .env wins over hard default
TENANT_COUNT="${_CALLER_TENANT_COUNT:-${TENANT_COUNT:-5}}"
NO_UP=false
for arg in "$@"; do
  [[ "$arg" == "--no-up" ]] && NO_UP=true
done

# Validate
if ! [[ "$TENANT_COUNT" =~ ^[1-9][0-9]*$ ]]; then
  echo "❌ TENANT_COUNT must be a positive integer, got: $TENANT_COUNT" >&2
  exit 1
fi

echo "▶ Generating docker-compose.yaml for $TENANT_COUNT tenant database(s)..."

OUTPUT="docker-compose.yaml"

# ──────────────────────────────────────────────────────────────────────────────
# Helper: compute host port for tenant DB index i (1-based)
# platform-db occupies 5434, so we skip it.
#   i=1 -> 5433
#   i=2 -> 5435
#   i=3 -> 5436  (5433 + i, skipping 5434)
# ──────────────────────────────────────────────────────────────────────────────
tenant_port() {
  local i=$1
  if [[ $i -eq 1 ]]; then
    echo 5433
  else
    echo $((5433 + i))
  fi
}

# ──────────────────────────────────────────────────────────────────────────────
# Build the depends_on block for axyra-agent (all tenant DBs + analytics)
# ──────────────────────────────────────────────────────────────────────────────
agent_depends=""
for i in $(seq 1 "$TENANT_COUNT"); do
  agent_depends+="      reference-db-${i}:
        condition: service_healthy
"
done
agent_depends+="      analytics:
        condition: service_healthy"

# ──────────────────────────────────────────────────────────────────────────────
# Generate tenant DB service blocks
# ──────────────────────────────────────────────────────────────────────────────
tenant_services=""
for i in $(seq 1 "$TENANT_COUNT"); do
  port=$(tenant_port "$i")
  tenant_services+="
  reference-db-${i}:
    image: postgres:16
    restart: unless-stopped
    environment:
      POSTGRES_USER: postgres
      POSTGRES_PASSWORD: postgres
      POSTGRES_DB: reference_db
    command: >
      postgres
        -c wal_level=logical
        -c max_replication_slots=4
        -c max_wal_senders=4
    volumes:
      - reference_db_${i}_data:/var/lib/postgresql/data
    ports:
      - \"${port}:5432\"
    healthcheck:
      test: [\"CMD-SHELL\", \"pg_isready -U postgres\"]
      interval: 5s
      timeout: 5s
      retries: 10
"
done

# ──────────────────────────────────────────────────────────────────────────────
# Generate volume declarations for tenant DBs
# ──────────────────────────────────────────────────────────────────────────────
tenant_volumes=""
for i in $(seq 1 "$TENANT_COUNT"); do
  tenant_volumes+="  reference_db_${i}_data:
"
done

# ──────────────────────────────────────────────────────────────────────────────
# Write the final docker-compose.yaml
# ──────────────────────────────────────────────────────────────────────────────
cat > "$OUTPUT" <<COMPOSE
# !! AUTO-GENERATED by generate-compose.sh — DO NOT EDIT BY HAND !!
# Re-generate with: cd deploy && ./generate-compose.sh --no-up
# TENANT_COUNT=${TENANT_COUNT}

services:

  # ─── Isolated Tenant Databases (${TENANT_COUNT} tenants) ─────────────────────────────
${tenant_services}
  # ─── Reference Client Backend (connects to tenant DB 1 for the demo UI) ──────

  reference-backend:
    build:
      context: ../reference-client/backend
    restart: unless-stopped
    environment:
      DATABASE_URL: postgresql+asyncpg://postgres:postgres@reference-db-1:5432/reference_db
      AXYRA_CONSOLE_URL: http://localhost:5173
    ports:
      - "8000:8000"
    depends_on:
      reference-db-1:
        condition: service_healthy
    healthcheck:
      test: ["CMD-SHELL", "curl -f http://localhost:8000/health || exit 1"]
      interval: 10s
      timeout: 5s
      retries: 5

  reference-frontend:
    build:
      context: ../reference-client/frontend
      dockerfile: Dockerfile
      args:
        VITE_API_URL: http://localhost:8000/api/v1
        VITE_AXYRA_URL: http://localhost:5173
    restart: unless-stopped
    ports:
      - "5174:80"
    depends_on:
      reference-backend:
        condition: service_healthy

  # ─── Axyra Agent (multi-source: one goroutine per tenant DB) ─────────────────

  axyra-agent:
    image: axyra-managed-agent:local
    build:
      context: ../agent
      dockerfile: Dockerfile
    restart: unless-stopped
    environment:
      AXYRA_ENDPOINT: http://analytics:8082
      AXYRA_AGENT_TOKEN: \${AXYRA_AGENT_TOKEN}
      TENANT_COUNT: \${TENANT_COUNT:-${TENANT_COUNT}}
    depends_on:
${agent_depends}
    volumes:
      - ../configs/agent-multitenant.yaml:/etc/axyra/agent.yaml:ro

  # ─── Axyra Platform ──────────────────────────────────────────────────────────

  platform-db:
    image: postgres:16
    restart: unless-stopped
    environment:
      POSTGRES_USER: postgres
      POSTGRES_PASSWORD: postgres
      POSTGRES_DB: axyra_platform
    volumes:
      - platform_db_data:/var/lib/postgresql/data
    ports:
      - "5434:5432"
    healthcheck:
      test: ["CMD-SHELL", "pg_isready -U postgres -d axyra_platform"]
      interval: 3s
      timeout: 3s
      retries: 15

  redis:
    image: redis:7-alpine
    restart: unless-stopped
    ports:
      - "6379:6379"
    healthcheck:
      test: ["CMD", "redis-cli", "ping"]
      interval: 5s
      timeout: 3s
      retries: 10

  control-plane:
    build:
      context: ../services/control-plane
      dockerfile: Dockerfile
    restart: unless-stopped
    environment:
      MANAGED_PROVISIONING_ENABLED: \${MANAGED_PROVISIONING_ENABLED:-false}
      DATABASE_URL: postgres://postgres:postgres@platform-db:5432/axyra_platform?sslmode=disable
      REDIS_URL: redis://redis:6379
      ANALYTICS_URL: http://analytics:8082
      AXYRA_COMPARISON_SOURCES: \${AXYRA_COMPARISON_SOURCES:-}
      AXYRA_COMPARISON_REFERENCE_DSN: postgres://postgres:postgres@reference-db-{index}:5432/reference_db?sslmode=disable
      AXYRA_SERVICE_TOKEN: \${AXYRA_SERVICE_TOKEN:?Set AXYRA_SERVICE_TOKEN in deploy/.env}
      AXYRA_AGENT_TOKEN: \${AXYRA_AGENT_TOKEN}
      JWT_SECRET: \${JWT_SECRET}
      AXYRA_ADMIN_PASSWORD: \${AXYRA_ADMIN_PASSWORD:-}
      AXYRA_OPERATOR_PASSWORD: \${AXYRA_OPERATOR_PASSWORD:-}
      TENANT_COUNT: \${TENANT_COUNT:-${TENANT_COUNT}}
      PORT: 8081
    ports:
      - "8081:8081"
    depends_on:
      platform-db:
        condition: service_healthy
      redis:
        condition: service_healthy
    healthcheck:
      test: ["CMD-SHELL", "curl -f http://localhost:8081/health || exit 1"]
      interval: 5s
      timeout: 3s
      retries: 10
      start_period: 10s

  provisioner:
    build:
      context: ../services/control-plane
      dockerfile: Dockerfile.provisioner
    profiles: ["managed"]
    restart: unless-stopped
    environment:
      DATABASE_URL: postgres://postgres:postgres@platform-db:5432/axyra_platform?sslmode=disable
      PROVISIONING_KEY: \${PROVISIONING_KEY:-}
      MANAGED_NETWORK: \${COMPOSE_PROJECT_NAME:-deploy}_default
      MANAGED_AGENT_IMAGE: axyra-managed-agent:local
      ANALYTICS_URL: http://analytics:8082
    volumes:
      - /var/run/docker.sock:/var/run/docker.sock
    depends_on:
      control-plane:
        condition: service_healthy
      analytics:
        condition: service_healthy

  analytics:
    build:
      context: ../services/analytics
      dockerfile: Dockerfile
    restart: unless-stopped
    environment:
      DATABASE_URL: postgres://postgres:postgres@platform-db:5432/axyra_platform?sslmode=disable
      REDIS_URL: redis://redis:6379
      CONTROL_PLANE_URL: http://control-plane:8081
      AXYRA_SERVICE_TOKEN: \${AXYRA_SERVICE_TOKEN:?Set AXYRA_SERVICE_TOKEN in deploy/.env}
      PORT: 8082
    expose:
      - "8082"
    depends_on:
      platform-db:
        condition: service_healthy
      redis:
        condition: service_healthy
      control-plane:
        condition: service_healthy
    healthcheck:
      test: ["CMD-SHELL", "curl -f http://localhost:8082/health || exit 1"]
      interval: 5s
      timeout: 3s
      retries: 10
      start_period: 10s

  # ─── Axyra Web Console ───────────────────────────────────────────────────────

  web:
    build:
      context: ../web
      dockerfile: Dockerfile
      args:
        VITE_API_URL: http://localhost:8081
    restart: unless-stopped
    ports:
      - "5173:80"
    depends_on:
      control-plane:
        condition: service_healthy
      analytics:
        condition: service_healthy

volumes:
${tenant_volumes}  platform_db_data:
COMPOSE

echo "✅ Generated $OUTPUT with $TENANT_COUNT tenant database(s)."
echo ""

# Port summary
echo "  Port layout:"
for i in $(seq 1 "$TENANT_COUNT"); do
  port=$(tenant_port "$i")
  store="store_$(printf "%03d" "$i")"
  echo "    reference-db-${i} ($store)  →  localhost:${port}"
done
echo "    platform-db              →  localhost:5434"
echo ""

if [[ "$NO_UP" == "true" ]]; then
  echo "  Skipping docker compose up (--no-up passed)."
  exit 0
fi

echo "▶ Running: docker compose up -d --build"
echo ""
docker compose up -d --build
